"""Write ``config/presets/*.yaml`` from the scenario table (keeps them in sync)."""

from __future__ import annotations

from pathlib import Path

import yaml

from ..config import PRESET_DIR

HEADER = ("# ANANTHAM preset (generated by `anantham presets` from bench/scenarios.py).\n"
          "# Only overrides of the defaults are listed; every other field keeps its PS default.\n")


def write_presets(directory: Path = PRESET_DIR) -> list[Path]:
    """Write default.yaml plus one YAML per benchmark scenario."""
    from .scenarios import SCENARIOS

    directory.mkdir(parents=True, exist_ok=True)
    out = []
    p = directory / "default.yaml"
    p.write_text(HEADER + "# default: circular motion, random start, mild sensor noise\n{}\n",
                 encoding="utf-8")
    out.append(p)
    for name, ov in SCENARIOS.items():
        p = directory / f"{name}.yaml"
        p.write_text(HEADER + yaml.safe_dump(ov, sort_keys=False), encoding="utf-8")
        out.append(p)
    return out
